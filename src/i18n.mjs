export function translate(text, language = 'es') {
  if (typeof text !== 'string') return text;
  return language === 'en' ? (EN[text] ?? text) : text;
}
export function formatLocalizedDate(iso, language = 'es') {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? '' : d.toLocaleString(languageToLocale(language));
}
