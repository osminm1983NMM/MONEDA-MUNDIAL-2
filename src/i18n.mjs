export function resolveAppLanguage(preference, deviceLocale = 'es') {
  if (preference === 'es' || preference === 'en') return preference;
  const tag = String(deviceLocale || 'es').toLowerCase().replace('_', '-');
  // Inglés para dispositivos en inglés; español seguro como idioma predeterminado
  // hasta que haya traducciones profesionales validadas para más lenguas.
  return tag === 'en' || tag.startsWith('en-') ? 'en' : 'es';
}

