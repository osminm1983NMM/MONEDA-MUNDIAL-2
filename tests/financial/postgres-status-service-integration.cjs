'use strict';
// Integration harness only: actual PostgreSQL prepared queries, disposable
// transaction and synthetic Auth responses. Never connects to remote Auth.
const {spawn}=require('node:child_process');
const {createInterface}=require('node:readline');
const assert=require('node:assert/strict');
const {createSupabaseOrderStatus}=require('../../financial-sandbox/supabase-order-status-auth.cjs');
const {createOrderStatusHttp,route}=require('../../financial-sandbox/order-status-http.cjs');
const {createOrderStatusClient}=require('../../financial-sandbox/order-status-client.cjs');
const {presentStatus}=require('../../financial-sandbox/order-status-presentation.cjs');
const {createRemittanceStatusHost}=require('../../financial-sandbox/mobile/remittance-status-host.js');
const {createRemittanceStatusPanel}=require('../../financial-sandbox/mobile/remittance-status-panel.js');
const container=process.env.LAB_CONTAINER;
if(!/^[a-f0-9]{12,64}$/.test(container||''))throw Error('CI_LAB_REQUIRED');
const owner='00000000-0000-4000-8000-000000000071',other='00000000-0000-4000-8000-000000000072';
const uuid=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const literal=v=>{if(typeof v!=='string'||!uuid.test(v))throw Error('FIXTURE_UUID_REQUIRED');return "'"+v+"'";};
const child=spawn('docker',['exec','-i',container,'psql','-X','-qAt','-v','ON_ERROR_STOP=1','-U','lab','-d','mwd_financial_sandbox_test'],{stdio:['pipe','pipe','pipe']});
const rl=createInterface({input:child.stdout});
let pending=null,sequence=0,stderr='',closed=false;
const rejectPending=error=>{if(pending){const p=pending;pending=null;clearTimeout(p.timer);p.reject(error);}};
child.stderr.setEncoding('utf8');child.stderr.on('data',x=>{stderr=(stderr+x).slice(-4000);});
child.stdin.on('error',rejectPending);
child.on('error',rejectPending);
const finished=new Promise(resolve=>child.on('close',code=>{closed=true;rejectPending(Error('PSQL_EXIT '+code+' '+stderr));resolve(code);}));
rl.on('line',line=>{
 if(!pending)return;
 if(line===pending.marker){const p=pending;pending=null;clearTimeout(p.timer);p.resolve(p.lines);}
 else if(line!=='')pending.lines.push(line);
});
function run(sql){
 if(closed||pending)throw Error('PSQL_NOT_READY');
 return new Promise((resolve,reject)=>{
  const marker='MWD_STATUS_END_'+(++sequence);
  pending={resolve,reject,marker,lines:[],timer:setTimeout(()=>{rejectPending(Error('PSQL_TIMEOUT '+stderr));child.kill();},15000)};
  child.stdin.write(sql+'\n\\echo '+marker+'\n');
 });
}
async function query(sql,params){
 // Use the exact SQL generated by the service. PREPARE retains $1/$2
 // bindings in PostgreSQL; EXECUTE accepts only the harness UUID fixtures.
 assert.ok(sql.startsWith('SELECT '));assert.equal(params.length,sql.includes('$2')?2:1);
 const lines=await run('PREPARE mwd_status_query AS SELECT row_to_json(q) FROM ('+sql+') q;\nEXECUTE mwd_status_query('+params.map(literal).join(',')+');\nDEALLOCATE mwd_status_query;');
 return {rows:lines.map(JSON.parse)};
}
async function main(){
 try{
  assert.deepEqual(await run('SELECT current_database();'),['mwd_financial_sandbox_test']);
  await run("BEGIN; SET LOCAL statement_timeout='10s'; SET LOCAL search_path=pg_catalog,mwd_financial_lab,pg_temp;\n"+
   "INSERT INTO actor_policy VALUES ("+literal(owner)+",'verified','clear','allow',50000),("+literal(other)+",'verified','clear','allow',50000);\n"+
   "INSERT INTO beneficiaries VALUES ("+literal(owner)+",'beneficiary','verified');\n"+
   "INSERT INTO status_bindings VALUES ("+literal(owner)+","+literal(owner)+",true),("+literal(other)+","+literal(other)+",true);\nSET LOCAL ROLE mwd_lab_order_service;");
  const [quoteId]=await run("SELECT quote_id FROM issue_quote("+literal(owner)+",'beneficiary',10000);");
  assert.match(quoteId,uuid);
  const [orderId]=await run("SELECT accept_quote("+literal(owner)+",'integration-status',"+literal(quoteId)+"::uuid,'sandbox-disclosure-v1');");
  assert.match(orderId,uuid);
  await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
  const service=createSupabaseOrderStatus({environment:'sandbox',authClient:{auth:{async getUser(token){
   const id=token==='owner-token'?owner:token==='other-token'?other:null;
   return id?{data:{user:{id,role:'authenticated',is_anonymous:false}},error:null}:{error:{status:401}};
  }}},query});
  const handle=createOrderStatusHttp({environment:'sandbox',service});
  const read=async sessionToken=>{
   const response=await handle(new Request('https://sandbox.invalid'+route,{method:'POST',headers:{authorization:'Bearer '+sessionToken,'content-type':'application/json'},body:JSON.stringify({orderId})}));
   assert.equal(response.headers.get('cache-control'),'no-store');
   return {status:response.status,body:await response.json()};
  };
  const r=await read('owner-token');
  assert.equal(r.status,200);assert.equal(r.body.status,'funding_pending');
  assert.deepEqual(r.body.source,{currency:'USD',principalMinor:'10000',feeMinor:'150',totalMinor:'10150'});
  assert.deepEqual(r.body.destination,{currency:'HNL',amountMinor:'250000'});
  assert.match(r.body.acceptedAt,/Z$/);
  assert.equal((await read('other-token')).status,404);
  assert.equal((await read('invalid-token')).status,401);
  const client=createOrderStatusClient({environment:'sandbox',sandboxOrigin:'https://sandbox.invalid',
   fetchImpl:(url,init)=>handle(new Request(url,init))});
  const result=await client.read({sessionToken:'owner-token',orderId});
  assert.equal(result.ok,true);
  const display=presentStatus(result.value,'es');
  assert.equal(display.total,'101,50 USD');
  assert.equal(display.destination,'2.500,00 HNL');
  assert.equal(display.warning,'PRUEBA — SIN DINERO REAL');
  assert.deepEqual(await client.read({sessionToken:'other-token',orderId}),{ok:false,code:'NOT_FOUND'});
  // Exercise the actual mobile composition across real lab database states.
  // Synthetic trusted events enter through the existing restricted event role.
  // This harness does not assert that an external provider has signed anything.
  let mobile;
  const host=createRemittanceStatusHost({environment:'sandbox',enabled:true,sandboxOrigin:'https://sandbox.invalid',
   expoFetch:(url,init)=>handle(new Request(url,init)),onChange:state=>{mobile=state;}});
  const Panel=createRemittanceStatusPanel({createElement:(type,props,...children)=>({type,props,children})},
   {View:'View',Text:'Text',TouchableOpacity:'TouchableOpacity'});
  const text=node=>typeof node==='string'?node:node?.children?.map(text).join(' ')||'';
  const refresh=async(label,id=orderId)=>{
   await host.refresh(id,mobile.selectionRevision);
   assert.equal(mobile.orderId,id);
   assert.equal(mobile.view.state,'ready');
   assert.equal(mobile.view.value.statusLabel,label);
   assert.equal(mobile.view.value.total,'101,50 USD');
   assert.equal(mobile.view.value.destination,'2.500,00 HNL');
   assert.ok(text(Panel({...mobile,onRefresh:host.refresh})).includes(label));
  };
  const counts=async(id=orderId)=>{
   await run('RESET ROLE;');
   const rows=await run("SELECT (SELECT count(*) FROM orders WHERE id="+literal(id)+"::uuid),"+
    "(SELECT count(*) FROM outbox WHERE order_id="+literal(id)+"::uuid),"+
    "(SELECT count(*) FROM journal WHERE order_id="+literal(id)+"::uuid);");
   await run('SET LOCAL ROLE mwd_lab_status_service;');
   return rows;
  };
  try{
   host.setSession('owner-token');host.selectOrder(orderId);
   const initial=await counts();
   assert.deepEqual(initial,['1|1|0']);
   await refresh('Financiación pendiente');
   assert.deepEqual(await counts(),initial);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_event_service;');
   assert.deepEqual(await run("SELECT record_verified_event('mock-remittance','status-integration-funding',"+literal(orderId)+"||'-funding','confirmed','USD',10150);"),['funded']);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
   await refresh('Financiación confirmada en prueba');
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_order_service;');
   await run("SELECT prepare_authorized("+literal(owner)+","+literal(orderId)+"::uuid,'payout');");
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
   await refresh('Entrega pendiente');
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_event_service;');
   assert.deepEqual(await run("SELECT record_verified_event('mock-remittance','status-integration-payout',"+literal(orderId)+"||'-payout','confirmed','HNL',250000);"),['paid']);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
   await refresh('Entrega confirmada en prueba');
   const settled=await counts();
   assert.deepEqual(settled,['1|2|2']);
   const obsoleteRevision=mobile.selectionRevision;
   host.setSession('other-token');host.selectOrder(orderId);
   await host.refresh(orderId,obsoleteRevision);
   assert.equal(mobile.view.state,'idle');
   await host.refresh(orderId,mobile.selectionRevision);
   assert.deepEqual(mobile.view,{state:'error',code:'NOT_FOUND'});
   assert.ok(!text(Panel({...mobile,onRefresh:host.refresh})).includes('101,50 USD'));
   assert.deepEqual(await counts(),settled);
   // Separate order: failed delivery and full refund, with the same read-only
   // native composition and independently checked journal and replay counts.
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_order_service;');
   const [refundQuote]=await run("SELECT quote_id FROM issue_quote("+literal(owner)+",'beneficiary',10000);");
   const [refundId]=await run("SELECT accept_quote("+literal(owner)+",'integration-status-refund',"+literal(refundQuote)+"::uuid,'sandbox-disclosure-v1');");
   assert.match(refundId,uuid);assert.notEqual(refundId,orderId);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
   host.setSession('owner-token');host.selectOrder(refundId);
   await refresh('Financiación pendiente',refundId);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_event_service;');
   assert.deepEqual(await run("SELECT record_verified_event('mock-remittance','status-refund-funding',"+literal(refundId)+"||'-funding','confirmed','USD',10150);"),['funded']);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_order_service;');
   await run("SELECT prepare_authorized("+literal(owner)+","+literal(refundId)+"::uuid,'payout');");
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_event_service;');
   assert.deepEqual(await run("SELECT record_verified_event('mock-remittance','status-refund-failed',"+literal(refundId)+"||'-payout','failed','HNL',250000);"),['payout_failed']);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
   await refresh('Entrega no completada',refundId);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_order_service;');
   await run("SELECT prepare_authorized("+literal(owner)+","+literal(refundId)+"::uuid,'refund');");
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
   await refresh('Devolución pendiente',refundId);
   const pendingRefund=await counts(refundId);
   assert.deepEqual(pendingRefund,['1|3|1']);
   await refresh('Devolución pendiente',refundId);
   assert.deepEqual(await counts(refundId),pendingRefund);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_event_service;');
   const refundEvent="SELECT record_verified_event('mock-remittance','status-refund-confirmed',"+literal(refundId)+"||'-refund','confirmed','USD',10150);";
   assert.deepEqual(await run(refundEvent),['refunded']);
   assert.deepEqual(await run(refundEvent),['duplicate']);
   await run('RESET ROLE; SET LOCAL ROLE mwd_lab_status_service;');
   await refresh('Devolución confirmada en prueba',refundId);
   assert.deepEqual(await counts(refundId),['1|3|2']);
   await run('RESET ROLE;');
   assert.deepEqual(await run('SELECT sum(cash),sum(payable),sum(revenue) FROM journal WHERE order_id='+literal(refundId)+';'),['0|0|0']);
   await run('SET LOCAL ROLE mwd_lab_status_service;');
   host.selectOrder(orderId);
   await refresh('Entrega confirmada en prueba');
   assert.deepEqual(await counts(),settled);
  }finally{host.dispose();}
  // Disable after identity resolution but before the actual status query.
  let revoked=false;
  const racing=createSupabaseOrderStatus({environment:'sandbox',authClient:{auth:{getUser:async()=>({data:{user:{id:owner,role:'authenticated',is_anonymous:false}},error:null})}},
   query:async(sql,params)=>{
    if(sql.includes('read_bound_order_status')&&!revoked){
     await run('RESET ROLE; UPDATE status_bindings SET active=false WHERE user_id='+literal(owner)+'; SET LOCAL ROLE mwd_lab_status_service;');revoked=true;
    }
    return query(sql,params);
   }});
  assert.equal((await racing.read({sessionToken:'owner-token',orderId})).status,404);
  assert.equal(revoked,true);assert.equal((await read('owner-token')).status,401);
  await run('RESET ROLE;');
  assert.deepEqual(await run('SELECT count(*) FROM orders WHERE actor='+literal(owner)+';'),['2']);
  assert.deepEqual(await run('SELECT count(*) FROM journal WHERE order_id='+literal(orderId)+';'),['2']);
  assert.deepEqual(await run('SELECT sum(cash),sum(payable),sum(revenue) FROM journal WHERE order_id='+literal(orderId)+';'),['150|0|-150']);
  await run('ROLLBACK;');
  assert.deepEqual(await run('SELECT count(*) FROM mwd_financial_lab.actor_policy WHERE actor='+literal(owner)+';'),['0']);
  console.log('Integrated Auth fixture, restricted PostgreSQL roles, mobile lifecycle, read-only invariants, settlement, refund replay and revocation verified');
 }finally{
  if(!closed)child.stdin.end('\\q\n');
  const code=await finished;
  if(code!==0)throw Error('PSQL_EXIT '+code+' '+stderr);
 }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
