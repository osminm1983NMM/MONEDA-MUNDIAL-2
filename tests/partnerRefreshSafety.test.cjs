// Comprobaciones estructurales: no sustituyen pruebas React Native ni Supabase.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const screen = fs.readFileSync(path.join(__dirname, '..', 'PartnerRegistryScreen.js'), 'utf8');
const start = screen.indexOf('  async function reloadPartners(');
const end = screen.indexOf('  async function reloadDetails(', start);
assert.ok(start >= 0 && end > start, 'Existe función de recarga');
const reload = screen.slice(start, end);
const invalidate = reload.indexOf('setDetailsReady(false)');
const request = reload.indexOf("request('mwd_owner_partners_demo')");
assert.ok(invalidate >= 0 && invalidate < request, 'Invalida detalles antes de la consulta');
assert.ok(reload.indexOf('setListReady(false)') < request, 'Invalida listado antes de la consulta');
const selected = screen.indexOf('  async function setStatus(');
const selectedEnd = screen.indexOf('  async function saveLocation(', selected);
assert.ok(screen.slice(selected, selectedEnd).includes('!detailsReady'), 'Estado exige detalles actualizados');
assert.ok(screen.includes('disabled={busy || !listReady || !detailsReady}'), 'Botón de estado exige listado y detalles vigentes');
assert.ok(screen.includes("detailsReady && audit.length === 0"), 'Historial vacío sólo tras consulta confirmada');
assert.ok(screen.includes('Historial no verificado:'), 'Advertencia si falta verificación del historial');
assert.ok(screen.includes('const requestNumber = ++partnersRequestRef.current'), 'Identificador para consultas del listado');
assert.ok(screen.includes("if (requestNumber !== partnersRequestRef.current) throw Error("), 'Descarta listados atrasados sin presentarlos como vacíos');
assert.ok(screen.includes('const requestNumber = ++detailsRequestRef.current'), 'Identificador para consultas de detalles');
assert.ok(screen.includes("if (requestNumber !== detailsRequestRef.current) throw Error("), 'Descarta detalles atrasados con error explícito');
assert.ok(screen.includes('disabled={busy || !listReady || !detailsReady || selected.review_status'), 'Botón de sucursal exige listado y detalles vigentes');
assert.ok(reload.includes('++detailsRequestRef.current;'), 'La recarga de socios invalida detalles pendientes');
assert.ok(screen.includes('!Array.isArray(loc) || !Array.isArray(hist)'), 'Rechaza formatos inválidos de detalles');
assert.ok(reload.includes('if (!Array.isArray(rows)) throw Error('), 'Recarga rechaza listados inválidos');
assert.ok(screen.includes('else if (!Array.isArray(data)) report('), 'Carga inicial rechaza listados inválidos');
assert.ok(screen.includes("typeof p.legal_name === 'string'"), 'Verifica campos esenciales de socios');
assert.ok(screen.includes("typeof l.display_name === 'string'"), 'Verifica campos esenciales de sucursales');
assert.ok(screen.includes("typeof a.changed_at === 'string'"), 'Verifica campos esenciales del historial');
console.log('18 comprobaciones estructurales de recuperación definidas.');
